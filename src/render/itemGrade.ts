import {
  BROKEN_ITEM_LIGHTNESS_SCALE,
  BROKEN_ITEM_SATURATION_SCALE,
} from '../config';

function rgbToHsl(r: number, g: number, b: number): [number, number, number] {
  const rn = r / 255;
  const gn = g / 255;
  const bn = b / 255;

  const max = Math.max(rn, gn, bn);
  const min = Math.min(rn, gn, bn);
  const l = (max + min) / 2;

  if (max === min) {
    return [0, 0, l];
  }

  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);

  let h = 0;
  if (max === rn) {
    h = (gn - bn) / d + (gn < bn ? 6 : 0);
  } else if (max === gn) {
    h = (bn - rn) / d + 2;
  } else {
    h = (rn - gn) / d + 4;
  }
  h /= 6;

  return [h, s, l];
}

function hueToRgb(p: number, q: number, t: number): number {
  let tn = t;
  if (tn < 0) tn += 1;
  if (tn > 1) tn -= 1;
  if (tn < 1 / 6) return p + (q - p) * 6 * tn;
  if (tn < 1 / 2) return q;
  if (tn < 2 / 3) return p + (q - p) * (2 / 3 - tn) * 6;
  return p;
}

function hslToRgb(h: number, s: number, l: number): [number, number, number] {
  if (s === 0) {
    const v = Math.round(l * 255);
    return [v, v, v];
  }

  const q = l < 0.5 ? l * (1 + s) : l + s - l * s;
  const p = 2 * l - q;

  const r = Math.round(hueToRgb(p, q, h + 1 / 3) * 255);
  const g = Math.round(hueToRgb(p, q, h) * 255);
  const b = Math.round(hueToRgb(p, q, h - 1 / 3) * 255);

  return [r, g, b];
}

export function buildBrokenItemPalette(palette: number[][]): number[][] {
  return palette.map((rgba) => {
    if (!rgba) return rgba;
    const [r, g, b, a = 255] = rgba;
    if (a === 0) {
      return rgba;
    }

    const [h, s, l] = rgbToHsl(r, g, b);
    const nextS = Math.max(0, Math.min(1, s * BROKEN_ITEM_SATURATION_SCALE));
    const nextL = Math.max(0, Math.min(1, l * BROKEN_ITEM_LIGHTNESS_SCALE));
    const [nr, ng, nb] = hslToRgb(h, nextS, nextL);

    return [nr, ng, nb, a];
  });
}
